"""Build safe Daangn Cafe post *drafts* from the public @jirum Telegram channel.

No website login, posting, or affiliate link generation. An original poster's
Coupang affiliate link must NEVER appear in the composed article.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import re
from urllib.parse import urlsplit

from gh_only.pipeline import enrich_posts, fetch_public_html
from gh_only.partner_api import safe_link

AFFILIATE_DISCLOSURE = "이 포스팅은 쿠팡 파트너스 활동의 일환으로, 이에 따른 일정액의 수수료를 제공받습니다."
LINK_PENDING = "[내 쿠팡 파트너스 링크 발급·검증 대기 — 발행 금지]"
KNOWN_CATEGORIES = {"coupang_shortlink", "coupang_product"}
HEADER_RE = re.compile(r"(?:무지성|대박|판매가|정상가|정가|최종가|할인가|가격\s*현황|특가\s*바로가기|배송비|선구매|쿠폰|할인|원문|가격\s*오류)", re.I)
URL_RE = re.compile(r"https?://\S+")
LEAD_RE = re.compile(r"^[\s🔥❤️✅💥👍📌📦⭐️⭐💰💸🛒•\-\u200b]+")
AMOUNT_RE = re.compile(r"\d[\d,]*\s*원")
DISCOUNT_LINE_RE = re.compile(r"^[\s\-•]*할인\s*[:：]")
SOURCE_MARKERS = ("이 포스팅은", "수수료", "특가 바로가기", "쿠팡 파트너스", "선구매후고민")


def normalized_title(source_text: str) -> str | None:
    """Skip hype/price headline; find first useful actual product-name line."""
    for raw in source_text.splitlines():
        line = LEAD_RE.sub("", raw.strip()).strip()
        if not (2 <= len(line) <= 150):
            continue
        if URL_RE.search(line) or HEADER_RE.search(line):
            continue
        if any(word in line for word in SOURCE_MARKERS):
            continue
        if AMOUNT_RE.search(line):
            continue
        if not any(c.isalnum() for c in line):
            continue
        return line[:100]
    return None


def notes_from_source(source_text: str, title: str | None) -> list[str]:
    """Only modest neutral product-note lines from source; no invented claims."""
    notes = []
    for raw in source_text.splitlines():
        line = LEAD_RE.sub("", raw.strip()).strip()
        if not line or line == title or URL_RE.search(line):
            continue
        if HEADER_RE.search(line) or AMOUNT_RE.search(line):
            continue
        if any(word in line for word in SOURCE_MARKERS):
            continue
        if not 4 <= len(line) <= 110:
            continue
        if not any(c.isalnum() for c in line):
            continue
        if line not in notes:
            notes.append(line)
        if len(notes) >= 3:
            break
    return notes


def link_proof_is_valid(proof: dict | None, deal: dict) -> bool:
    """Separate owning a URL from verifying that it represents this exact deal.

    A caller-supplied URL ALONE isn't proof of ownership or item matching.
    Proof must be generated by an independently validated affiliate adapter.
    """
    if not isinstance(proof, dict):
        return False
    if proof.get("method") != "approved_partners_api_verified":
        return False
    if not proof.get("own_account_confirmed") or not proof.get("item_identity_confirmed"):
        return False
    if not deal.get("product_id") or not deal.get("item_id"):
        return False
    if str(proof.get("product_id")) != str(deal["product_id"]):
        return False
    if str(proof.get("item_id")) != str(deal["item_id"]):
        return False
    dv, pv = deal.get("vendor_item_id"), proof.get("vendor_item_id")
    if dv and str(pv) != str(dv):
        return False
    if not safe_link(proof.get("own_affiliate_url")):
        return False
    return True


def build_draft(deal: dict, proof: dict | None = None) -> dict | None:
    # Exclude other merchants; only Coupang deals are in scope.
    if deal.get("url_kind") not in KNOWN_CATEGORIES:
        return None
    source_text = deal.get("source_text") or ""
    title = normalized_title(source_text)
    if not title:
        return None
    sale = deal.get("sale_price_krw")
    original = deal.get("original_price_krw")
    image = deal.get("image_url_candidate")
    image_origin = deal.get("image_provenance")
    proof_ok = link_proof_is_valid(proof, deal)
    own_link = proof["own_affiliate_url"] if proof_ok else None

    lines = [f"📦 {title}", "", "뽐질 텔레그램 채널에 소개된 상품 정보입니다."]
    if sale:
        lines.append(f"💰 게시글 표기 특가: {sale:,}원")
    else:
        lines.append("💰 게시글 특가: 가격 확인 필요")
    if original:
        lines.append(f"🏷️ 게시글 표기 정상가: {original:,}원")
    if sale and original and deal.get("discount_percent_computed") is not None:
        lines.append(f"📉 게시글 가격 기준 할인율: {deal['discount_percent_computed']:.1f}%")
    lines.append("")
    for note in notes_from_source(source_text, title):
        lines.append("• " + note)
    if image:
        lines.append("🖼️ 이미지: 텔레그램 출처 후보(정확한 옵션 사진 미검증)")
    else:
        lines.append("🖼️ 첨부 가능한 상품 사진 미확보")
    lines.extend(["", "🛒 상품 구매 링크", own_link or LINK_PENDING, "",
                  "※ 가격은 텔레그램 게시글에서 추출한 정보이며, 실제 판매 가격과 옵션은 달라질 수 있습니다."])
    if own_link:
        lines.append(AFFILIATE_DISCLOSURE)

    blockers = []
    if not sale:
        blockers.append("PRICE_NOT_UNAMBIGUOUS")
    if not image:
        blockers.append("PRODUCT_IMAGE_MISSING")
    else:
        blockers.append("IMAGE_NOT_VERIFIED_FOR_EXACT_OPTION")
    if not proof_ok:
        blockers.append("PERSONAL_AFFILIATE_URL_NOT_VERIFIED")
    if not deal.get("exact_option_verified"):
        blockers.append("PRODUCT_ITEM_ID_NOT_VERIFIED_FROM_COUPANG")
    blockers.append("DAANGN_PUBLISHER_NOT_CONNECTED")
    return {
        "source_post_id": deal["source_message_id"],
        "source_post_url": deal["source_post_url"],
        "title": title,
        "article_body": "\n".join(lines),
        "photo_candidate": image,
        "photo_origin": image_origin,
        "price_origin": deal.get("price_provenance"),
        "sale_price_krw": sale,
        "original_price_krw": original,
        "own_affiliate_url": own_link,
        "status": "DRAFT_ONLY_DO_NOT_PUBLISH",
        "publish_ready": False,
        "blockers": blockers,
    }


def build_bundle_from_records(records: list[dict]) -> dict:
    drafts = [build_draft(record) for record in records]
    drafts = [draft for draft in drafts if draft is not None]
    return {
        "schema": "github-only-daangn-drafts-v1",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "source": "public_telegram_jirum",
        "source_total": len(records),
        "coupang_draft_count": len(drafts),
        "published_count": 0,
        "notes": "All prices from Telegram, photos are unverified, original affiliate URLs excluded. No posts sent.",
        "drafts": drafts,
    }

def build_bundle(html: str, max_posts: int = 8) -> dict:
    return build_bundle_from_records(enrich_posts(html, max_posts=max_posts))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=("fixture", "live", "evidence"), default="fixture")
    parser.add_argument("--evidence-json")
    parser.add_argument("--fixture-html")
    parser.add_argument("--output", default="gh_only_daangn_drafts.json")
    args = parser.parse_args()
    if args.mode == "evidence":
        if not args.evidence_json:
            raise ValueError("evidence_json_required")
        evidence = json.loads(Path(args.evidence_json).read_text(encoding="utf-8"))
        if evidence.get("schema") != "github-only-deal-probe.v1":
            raise ValueError("unexpected_source_evidence")
        result = build_bundle_from_records(evidence["deals"])
    elif args.mode == "fixture":
        if not args.fixture_html:
            raise ValueError("fixture_html_required")
        result = build_bundle(Path(args.fixture_html).read_text(encoding="utf-8"))
    else:
        result = build_bundle(fetch_public_html())
    Path(args.output).write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n",
                                 encoding="utf-8")
    print("JIRUM_DAANGN_DRAFTS " + json.dumps({
        "source_total": result["source_total"],
        "coupang_draft_count": result["coupang_draft_count"],
        "published_count": 0,
        "affiliate_links_injected": 0,
        "image_candidates": sum(bool(d["photo_candidate"]) for d in result["drafts"]),
        "prices_available": sum(bool(d["sale_price_krw"]) for d in result["drafts"]),
    }, ensure_ascii=False))


if __name__ == "__main__":
    main()
